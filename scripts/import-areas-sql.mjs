#!/usr/bin/env node
/* THE SPORTS' AREAS, AS THE DATABASE CHECKS THEM.
 *
 * An imported lesson's focus is a set of the sport's own areas joined
 * with " · " — and import_lessons() in supabase/nosca.sql refuses any part
 * that is not one of them (or "Lesson" / "Practice"), so a chat imported
 * by a player can never carry words of its own into the focus. The list
 * it checks against is public.import_areas, filled by one generated block
 * of nosca.sql from src/lib/taxonomy.js — the same FOCUS the app draws
 * the log's areas from. Nobody types it.
 *
 *   node scripts/import-areas-sql.mjs           prints the block
 *   node scripts/import-areas-sql.mjs --write   puts it between the markers in nosca.sql
 *   node scripts/import-areas-sql.mjs --check   exits 1 when nosca.sql's block differs
 *
 * `npm run check` runs --check, so a label changed in taxonomy.js and not
 * in the SQL stops before a deploy does.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { FOCUS } from "../src/lib/taxonomy.js";

const SQL = fileURLToPath(new URL("../supabase/nosca.sql", import.meta.url));
const OPEN = "-- >>> import_areas";
const CLOSE = "-- <<< import_areas";
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function areasBlock() {
  const rows = [];
  for (const [sport, areas] of Object.entries(FOCUS)) for (const a of areas) rows.push(`(${q(sport)}, ${q(a.label)})`);
  const list = rows.map((r) => `  ${r}`).join(",\n");
  return [
    `${OPEN} (generated by scripts/import-areas-sql.mjs from src/lib/taxonomy.js; npm run check compares)`,
    "insert into public.import_areas (sport, label) values",
    list,
    "on conflict do nothing;",
    "delete from public.import_areas where (sport, label) not in (values",
    list,
    ");",
    CLOSE,
  ].join("\n");
}

function current(sql) {
  const a = sql.indexOf(OPEN), b = sql.indexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) return null;
  return { a, b: b + CLOSE.length, text: sql.slice(a, b + CLOSE.length) };
}

const mode = process.argv[2] || "";
if (mode === "--write" || mode === "--check") {
  const sql = readFileSync(SQL, "utf8");
  const have = current(sql);
  const want = areasBlock();
  if (!have) { console.error("nosca.sql has no import_areas markers"); process.exit(1); }
  if (mode === "--check") {
    if (have.text !== want) {
      console.error("supabase/nosca.sql's import_areas block differs from src/lib/taxonomy.js — run: node scripts/import-areas-sql.mjs --write");
      process.exit(1);
    }
    console.log("import_areas: nosca.sql matches taxonomy.js");
  } else {
    writeFileSync(SQL, sql.slice(0, have.a) + want + sql.slice(have.b));
    console.log("import_areas: written into supabase/nosca.sql");
  }
} else if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(areasBlock());
}
